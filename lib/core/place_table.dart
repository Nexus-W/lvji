/// 坐标 → 最近地名 + 距离（度²）。内部唯一实现，其它地方不要各自再算距离。
(String, double) nearestPlaceWithDist(double lat, double lng) {
  var best = cityTable.first;
  var bestDist = double.infinity;
  for (final c in cityTable) {
    final d = (c.$2 - lat) * (c.$2 - lat) + (c.$3 - lng) * (c.$3 - lng);
    if (d < bestDist) {
      bestDist = d;
      best = c;
    }
  }
  return (best.$1, bestDist);
}

/// 坐标 → 最近地名（超出覆盖范围返回空串）。
///
/// 城市表只覆盖中国主要城市。不设距离上限的话，波兰/泰国的照片也会被
/// 填成最近的中国城市，后续修复逻辑还会拿这个名字覆盖真实坐标。
/// 阈值与 `cityOf` 一致：0.36 度²（约 0.6°，60km）。
String nearestPlace(double lat, double lng) {
  final (name, dist) = nearestPlaceWithDist(lat, lng);
  return dist < 0.36 ? name : '';
}

/// 地名 → 坐标（最长匹配优先：「杭州」不会错配到「杭州东」）。
(double?, double?) placeToLatLng(String place) {
  final p = place.trim();
  if (p.isEmpty) return (null, null);
  String? bestName;
  for (final c in cityTable) {
    if (p == c.$1) return (c.$2, c.$3);
    if (p.contains(c.$1) || c.$1.contains(p)) {
      if (bestName == null || c.$1.length > bestName.length) {
        bestName = c.$1;
      }
    }
  }
  if (bestName == null) return (null, null);
  for (final c in cityTable) {
    if (c.$1 == bestName) return (c.$2, c.$3);
  }
  return (null, null);
}
